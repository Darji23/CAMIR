"""Resumable trace collection script for CAMIR.

Executes real inference across:
- Small Tier: Local MLX Qwen2.5-1.5B (4-bit)
- Medium Tier: Local MLX Qwen2.5-7B (4-bit)
- Large Tier: Hosted API (Fireworks AI Qwen 3.8 Max / Qwen-72B)
- Verification traces: Prefill forward pass scoring using 7B verifier on Apple Silicon

Saves traces with guaranteed idempotency to SQLite (skips already-collected rows).
Zero mock data: all traces are generated by real model inference on real datasets.
"""

import argparse
import json
from pathlib import Path
from typing import Dict, List
from rich.console import Console
from rich.progress import track

from camir.tiers.hosted_api import HostedAPITier
from camir.tiers.mlx_local import LocalMLXTier, MediumMLXTier
from camir.traces.collector import TraceCollector
from camir.traces.store import TraceStore
from camir.utils.env import load_env
from camir.utils.hardware import get_hardware_info, get_thermal_state

console = Console()
DATA_DIR = Path(__file__).resolve().parent.parent / "data"


def load_dataset(path: Path) -> List[Dict]:
    if not path.exists():
        return []
    with open(path, "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    parser = argparse.ArgumentParser(description="Collect real inference traces across CAMIR tiers.")
    parser.add_argument(
        "--input",
        type=str,
        default="data/test_group.jsonl",
        help="Input JSONL prompt file (default: data/test_group.jsonl).",
    )
    parser.add_argument(
        "--per-dataset",
        type=int,
        default=5,
        help="Number of prompts to trace per dataset (default: 5, use 0 for all).",
    )
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=128,
        help="Max generation tokens per tier (default: 128).",
    )
    parser.add_argument(
        "--skip-medium",
        action="store_true",
        help="Skip medium tier generation.",
    )
    parser.add_argument(
        "--skip-large",
        action="store_true",
        help="Skip hosted large tier generation.",
    )
    args = parser.parse_args()

    load_env()

    console.rule("[bold cyan]CAMIR: Real Multi-Tier Trace Collector[/bold cyan]")
    console.print(f"Hardware: [dim]{get_hardware_info()}[/dim] | Thermal State: [dim]{get_thermal_state()}[/dim]")

    input_path = Path(args.input)
    if not input_path.exists():
        console.print(f"[bold red]Input file {input_path} not found.[/bold red]")
        return

    all_prompts = load_dataset(input_path)
    console.print(f"Loaded {len(all_prompts)} total prompts from {input_path.name}")

    # Select prompts (stratified per dataset if per-dataset > 0)
    if args.per_dataset > 0:
        by_ds: Dict[str, List[Dict]] = {}
        for p in all_prompts:
            by_ds.setdefault(p["dataset"], []).append(p)
        selected_prompts = []
        for ds, items in by_ds.items():
            selected_prompts.extend(items[: args.per_dataset])
    else:
        selected_prompts = all_prompts

    console.print(f"Selected [bold]{len(selected_prompts)}[/bold] prompts to trace across tiers.")

    store = TraceStore()

    # Initialize Real Tiers (no mock mode)
    console.print("\n[bold]Initializing Real Model Tiers...[/bold]")
    small = LocalMLXTier(model_id="mlx-community/Qwen2.5-1.5B-Instruct-4bit", tier_name="small")
    console.print(f"  Small Tier:  [green]{small.model_id}[/green] (MLX Apple Silicon)")

    medium = None
    if not args.skip_medium:
        medium = MediumMLXTier(model_id="mlx-community/Qwen2.5-7B-Instruct-4bit", tier_name="medium")
        console.print(f"  Medium Tier: [green]{medium.model_id}[/green] (MLX Apple Silicon)")

    hosted = None
    if not args.skip_large:
        hosted = HostedAPITier(tier_name="large")
        console.print(f"  Large Tier:  [green]{hosted.model_id}[/green] (Hosted Fireworks API)")

    collector = TraceCollector(
        store=store,
        small_tier=small,
        medium_tier=medium,
        hosted_tier=hosted,
    )

    console.print("\n[bold]Collecting traces (idempotent; skips existing cached rows)...[/bold]")
    new_collected = 0
    for item in track(selected_prompts, description="Tracing prompts..."):
        traces = collector.collect_prompt_traces(
            prompt_item=item,
            max_tokens=args.max_tokens,
            skip_medium=args.skip_medium,
            skip_large=args.skip_large,
        )
        new_collected += len(traces)

    total_traces = store.count_traces()
    console.print(f"\n[bold green]✓ Trace Collection Complete![/bold green]")
    console.print(f"Processed prompts: {len(selected_prompts)}")
    console.print(f"Total traces now in SQLite: [bold cyan]{total_traces}[/bold cyan]")


if __name__ == "__main__":
    main()
